from pathlib import Path

from silo.build_profile import Profile
from silo.options import Options
from silo.platform import backend_for
from silo.silo_package import SiloPackage

TOOLCHAIN_FILE = "silo-toolchain.cmake"
CACHE_FILE = "silo-cache.cmake"
CONFIGS_DIR = "cmake"
# Written by CMakeDeps, next to the configs
RUNTIME_FILE = "silo-runtime.cmake"
HEADER = "# Generated by silo. Changes are overwritten."

# Make find_package() see silo's generated configs and nothing registered on the machine.
# PREFER_CONFIG matters because CMake otherwise tries its own FindZLIB-style modules first.
SYSTEM_PATH_SWITCH = "CMAKE_FIND_USE_CMAKE_SYSTEM_PATH"
ISOLATION = {
    "CMAKE_FIND_USE_PACKAGE_REGISTRY": "OFF",
    "CMAKE_FIND_USE_SYSTEM_PACKAGE_REGISTRY": "OFF",
    SYSTEM_PATH_SWITCH: "OFF",
    "CMAKE_FIND_PACKAGE_PREFER_CONFIG": "ON",
}


def toolchain_text(profile: Profile, system_packages: bool = False) -> str:
    """A toolchain file that serves debug and release builds alike.

    `system_packages` lets find_package() also search the machine's own folders.
    """
    backend = backend_for(profile.settings.os)
    variables = {
        "CMAKE_C_COMPILER": profile.compiler.executable.as_posix(),
        "CMAKE_CXX_COMPILER": profile.compiler.cxx.as_posix(),
        "CMAKE_CXX_STANDARD": str(profile.settings.cppstd),
        **ISOLATION,
        **backend.cmake_cache_entries(profile),
    }
    if system_packages:
        del variables[SYSTEM_PATH_SWITCH]
    defines = backend.hardening_defines(profile)
    if defines:
        # _INIT adds to CMake's default flags, where CMAKE_CXX_FLAGS_DEBUG would replace them
        variables["CMAKE_CXX_FLAGS_DEBUG_INIT"] = " ".join(f"-D{define}" for define in defines)

    lines = [HEADER]
    lines += [f'set({key} "{value}")' for key, value in variables.items()]
    lines.append(f'list(PREPEND CMAKE_PREFIX_PATH "${{CMAKE_CURRENT_LIST_DIR}}/{CONFIGS_DIR}")')
    lines.append(f'include("${{CMAKE_CURRENT_LIST_DIR}}/{CONFIGS_DIR}/{RUNTIME_FILE}" OPTIONAL)')
    return "\n".join(lines) + "\n"


def cache_text(cache: dict[str, tuple[str, str]]) -> str:
    """An initial cache file for `cmake -C`.

    A toolchain file is read at project(), too late for an option() declared before it.
    This file is read before the project's build files.
    """
    entries = [
        f'set({key} "{value}" CACHE {kind} "" FORCE)' for key, (kind, value) in cache.items()
    ]
    return "\n".join([HEADER, *entries]) + "\n"


class CMakeGenerator[T: Options = Options]:
    """Writes the toolchain file that points a CMake build at silo's compiler and dependencies.

    Cache entries a recipe adds go into a second file, which CMakeBuild loads first.
    CMakePresets, which is given this generator, repeats them in its hidden preset.
    """

    def __init__(self, package: SiloPackage[T]) -> None:
        self.package: SiloPackage[T] = package
        self._cache: dict[str, tuple[str, str]] = {}
        self._system_packages = False

    def allow_system_packages(self):
        """Let find_package() fall back to the machine, for what no recipe provides."""
        self._system_packages = True

    def add_cache_string(self, key: str, value: str):
        self._cache[key] = ("STRING", value)

    def add_cache_bool(self, key: str, value: bool):
        self._cache[key] = ("BOOL", "ON" if value else "OFF")

    @property
    def cache(self) -> dict[str, str]:
        return {key: value for key, (_, value) in self._cache.items()}

    def generate(self) -> Path:
        context = self.package.context
        context.generated_dir.mkdir(parents=True, exist_ok=True)
        toolchain = context.generated_dir / TOOLCHAIN_FILE
        text = toolchain_text(context.profile, self._system_packages)
        toolchain.write_text(text, encoding="utf-8")
        if self._cache:
            cache_file = context.generated_dir / CACHE_FILE
            cache_file.write_text(cache_text(self._cache), encoding="utf-8")
        return toolchain
