import shutil
from pathlib import Path
from typing import Any

from silo.enums import BuildMode, RuntimeLibrary
from silo.platform import backend_for
from silo.silo_package import SiloPackage
from silo.tools.pkgconfig.pkg_config_deps import PC_DIR

NATIVE_FILE = "silo-meson.ini"
HEADER = "# Generated by silo. Changes are overwritten."

VS_RUNTIME = {RuntimeLibrary.DynamicRelease: "md"}

OptionValue = str | bool | int | list[str]


def _quoted(value: OptionValue) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(_quoted(item) for item in value) + "]"
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _section(name: str, entries: dict[str, OptionValue]) -> list[str]:
    return [f"[{name}]", *(f"{key} = {_quoted(value)}" for key, value in entries.items()), ""]


class MesonGenerator:
    """Writes the native file that points a Meson build at silo's compiler and dependencies.

    Dependencies are found through pkg-config, so a recipe that has any also runs
    PkgConfigDeps and declares self.tool("pkgconf@...").
    """

    def __init__(self, package: SiloPackage[Any]) -> None:
        self.package = package
        self.project_options: dict[str, OptionValue] = {}
        self.builtin_options: dict[str, OptionValue] = {}

    def set_option(self, key: str, value: OptionValue) -> None:
        """One of the project's own options, from its meson_options.txt."""
        self.project_options[key] = value

    def set_builtin(self, key: str, value: OptionValue) -> None:
        """One of Meson's options, such as default_library."""
        self.builtin_options[key] = value

    def generate(self) -> Path:
        context = self.package.context
        profile = context.profile
        binaries: dict[str, OptionValue] = {
            "c": profile.compiler.executable.as_posix(),
            "cpp": profile.compiler.cxx.as_posix(),
        }
        pkg_config = shutil.which("pkgconf", path=context.env["PATH"])
        if pkg_config:
            binaries["pkg-config"] = Path(pkg_config).as_posix()

        debug = context.build_type is BuildMode.Debug
        builtin: dict[str, OptionValue] = {
            "buildtype": "debug" if debug else "release",
            "prefix": context.install_prefix,
            "libdir": "lib",
            "default_library": "static",
            # A dependency that is missing fails the build instead of being downloaded
            "wrap_mode": "nodownload",
            "pkg_config_path": (context.generated_dir / PC_DIR).as_posix(),
        }
        backend = backend_for(profile.settings.os)
        runtime = backend.runtime_library(profile)
        if runtime:
            builtin["b_vscrt"] = VS_RUNTIME[runtime]
        flags = backend.cxx_flags(profile)
        if flags:
            builtin["cpp_args"] = flags
        if backend.runtime_search:
            search = [f"-Wl,-rpath,{folder}" for folder in backend.runtime_search]
            builtin["c_link_args"] = builtin["cpp_link_args"] = search
        builtin |= self.builtin_options
        lines = [HEADER, *_section("binaries", binaries), *_section("built-in options", builtin)]
        if self.project_options:
            lines += _section("project options", self.project_options)

        context.generated_dir.mkdir(parents=True, exist_ok=True)
        native_file = context.generated_dir / NATIVE_FILE
        native_file.write_text("\n".join(lines), encoding="utf-8", newline="\n")
        return native_file
